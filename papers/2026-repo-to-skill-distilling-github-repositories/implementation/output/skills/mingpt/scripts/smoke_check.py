"""smoke_check.py — static sanity probe for a minGPT checkout.

Generated by the deterministic repo-to-skill distiller. Usage:

    python3 smoke_check.py /path/to/minGPT

It only READS the checkout (no repo code is executed): verifies the files
that the skill's evidence is grounded in still exist and contain the
symbols this skill documents.
"""
import os, re, sys

EXPECT_FILES = ['mingpt/bpe.py', 'mingpt/model.py', 'mingpt/trainer.py', 'mingpt/utils.py', 'projects/adder/adder.py', 'projects/chargpt/chargpt.py', 'tests/test_huggingface_import.py']
EXPECT_SYMBOLS = ['AdditionDataset', 'BPETokenizer', 'Block', 'CausalSelfAttention', 'CfgNode', 'CharDataset', 'Encoder', 'GPT', 'NewGELU', 'TestHuggingFaceImport', 'Trainer', 'bytes_to_unicode', 'get_config', 'get_encoder', 'get_file', 'get_pairs', 'set_seed', 'setup_logging']

def main(root):
    ok = True
    for rel in EXPECT_FILES:
        if not os.path.exists(os.path.join(root, rel)):
            print(f"MISS  file   {rel}"); ok = False
        else:
            print(f"ok    file   {rel}")
    for rel in EXPECT_FILES:
        p = os.path.join(root, rel)
        if not os.path.exists(p):
            continue
        src = open(p, encoding="utf-8", errors="replace").read()
        for sym in EXPECT_SYMBOLS:
            if re.search(r"\b{}\b".format(re.escape(sym)), src):
                print(f"ok    symbol {sym} in {rel}")
    sys.exit(0 if ok else 1)

if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
